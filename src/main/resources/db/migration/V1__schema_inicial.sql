-- Esquema inicial (ADR-001). criado_por/atualizado_por guardam o "sub" do Keycloak (UUID).

CREATE TABLE produto (
    id_produto      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            VARCHAR(120)   NOT NULL,
    descricao       VARCHAR(500),
    preco           NUMERIC(10, 2) NOT NULL CHECK (preco >= 0),
    qt_estoque      INTEGER        NOT NULL DEFAULT 0 CHECK (qt_estoque >= 0),
    versao          BIGINT         NOT NULL DEFAULT 0,
    criado_por      UUID,
    criado_em       TIMESTAMPTZ    NOT NULL DEFAULT now(),
    atualizado_por  UUID,
    atualizado_em   TIMESTAMPTZ,
    deletado_por    UUID,
    deletado_em     TIMESTAMPTZ
);

-- Nome único só entre produtos ativos: um produto "deletado" não bloqueia o nome
CREATE UNIQUE INDEX uk_produto_nome_ativo ON produto (lower(nome)) WHERE deletado_em IS NULL;

CREATE TABLE pedido (
    id_pedido       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status          VARCHAR(20)    NOT NULL CHECK (status IN ('ABERTO', 'CONFIRMADO', 'CANCELADO')),
    total           NUMERIC(12, 2) NOT NULL CHECK (total >= 0),
    versao          BIGINT         NOT NULL DEFAULT 0,
    criado_por      UUID,
    criado_em       TIMESTAMPTZ    NOT NULL DEFAULT now(),
    atualizado_por  UUID,
    atualizado_em   TIMESTAMPTZ
);

CREATE INDEX idx_pedido_status ON pedido (status);

CREATE TABLE item_pedido (
    id_item         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido       BIGINT         NOT NULL REFERENCES pedido (id_pedido) ON DELETE CASCADE,
    id_produto      BIGINT         NOT NULL REFERENCES produto (id_produto),
    quantidade      INTEGER        NOT NULL CHECK (quantidade > 0),
    vl_unitario     NUMERIC(10, 2) NOT NULL CHECK (vl_unitario >= 0),
    CONSTRAINT uk_item_pedido_produto UNIQUE (id_pedido, id_produto)
);

CREATE INDEX idx_item_pedido_produto ON item_pedido (id_produto);

-- Imutável: sem colunas de atualização nem de exclusão
CREATE TABLE movimentacao_estoque (
    id_movimentacao BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_produto      BIGINT       NOT NULL REFERENCES produto (id_produto),
    id_pedido       BIGINT       REFERENCES pedido (id_pedido),
    tipo            VARCHAR(10)  NOT NULL CHECK (tipo IN ('ENTRADA', 'SAIDA')),
    motivo          VARCHAR(30)  NOT NULL CHECK (motivo IN ('PEDIDO', 'CANCELAMENTO_PEDIDO', 'AJUSTE', 'PERDA', 'INVENTARIO', 'REPOSICAO')),
    quantidade      INTEGER      NOT NULL CHECK (quantidade > 0),
    saldo_anterior  INTEGER      NOT NULL CHECK (saldo_anterior >= 0),
    saldo_posterior INTEGER      NOT NULL CHECK (saldo_posterior >= 0),
    observacao      VARCHAR(255),
    criado_por      UUID         NOT NULL,
    criado_em       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_mov_saldo CHECK (
        (tipo = 'ENTRADA' AND saldo_posterior = saldo_anterior + quantidade) OR
        (tipo = 'SAIDA'   AND saldo_posterior = saldo_anterior - quantidade)
    )
);

CREATE INDEX idx_mov_produto_data ON movimentacao_estoque (id_produto, criado_em);
CREATE INDEX idx_mov_pedido ON movimentacao_estoque (id_pedido) WHERE id_pedido IS NOT NULL;
